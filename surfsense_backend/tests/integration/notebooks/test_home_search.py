async def test_other_workspaces_are_invisible(
    db_session, make_owner, make_document, make_notebook
):
    owner = await make_owner()
    stranger = await make_owner()
    theirs = await make_document(stranger.workspace.id, "Theirs", "Asthma secrets.")
    their_nb = await make_notebook(
        stranger.workspace.id, "Theirs", sources=[("document", theirs.id)]
    )
    db_session.add(
        NotebookNote(notebook_id=their_nb.id, title="Asthma note", content="Asthma")
    )
    # A forged link from our notebook to their document must not leak it.
    ours = await make_notebook(
        owner.workspace.id, "Ours", sources=[("document", theirs.id)]
    )
    await db_session.flush()

    result = await _search(db_session, owner, "asthma")
    assert result.notebooks == []
    assert ours.id not in _by_notebook(result)

    # And the stranger cannot search the owner's workspace at all.
    with pytest.raises(HTTPException) as exc:
        await _search(db_session, stranger, "asthma", workspace_id=owner.workspace.id)
    assert exc.value.status_code == 403


async def test_viewer_can_search_but_without_document_access_sees_notes_only(
    db_session, make_owner, make_user, add_member, make_document, make_notebook
):
    owner = await make_owner()
    ws = owner.workspace.id
    doc = await make_document(ws, "Paper", "Budesonide nebulised.")
    notebook = await make_notebook(ws, "Nb", sources=[("document", doc.id)])
    db_session.add(
        NotebookNote(notebook_id=notebook.id, title="Plan", content="Budesonide daily.")
    )
    await db_session.flush()

    viewer = await make_user()
    await add_member(owner.workspace, viewer, "Viewer")
    seen = await _search(db_session, _as(owner, viewer), "budesonide")
    kinds = {p.kind for p in _by_notebook(seen)[notebook.id]}
    assert kinds == {"source", "note"}

    chats_only = WorkspaceRole(
        name=f"Chats only {uuid.uuid4().hex[:4]}",
        workspace_id=ws,
        permissions=[Permission.CHATS_READ.value],
    )
    db_session.add(chats_only)
    await db_session.flush()
    reader = await make_user()
    db_session.add(
        WorkspaceMembership(
            user_id=reader.id, workspace_id=ws, role_id=chats_only.id, is_owner=False
        )
    )
    await db_session.flush()
    limited = await _search(db_session, _as(owner, reader), "budesonide")
    assert {p.kind for p in _by_notebook(limited)[notebook.id]} == {"note"}

    nobody = WorkspaceRole(
        name=f"Nothing {uuid.uuid4().hex[:4]}", workspace_id=ws, permissions=[]
    )
    db_session.add(nobody)
    await db_session.flush()
    blocked = await make_user()
    db_session.add(
        WorkspaceMembership(
            user_id=blocked.id, workspace_id=ws, role_id=nobody.id, is_owner=False
        )
    )
    await db_session.flush()
    with pytest.raises(HTTPException) as exc:
        await _search(db_session, _as(owner, blocked), "budesonide")
    assert exc.value.status_code == 403


