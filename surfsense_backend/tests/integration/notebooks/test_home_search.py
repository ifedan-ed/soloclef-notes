class _FakeReranker:
    """Scores a passage 0.9 if it mentions 'guideline', else 0.01."""

    def rerank_documents(self, query, documents):
        scored = [
            {**d, "score": 0.9 if "guideline" in d["content"].lower() else 0.01}
            for d in documents
        ]
        return sorted(scored, key=lambda d: -d["score"])


async def test_reranker_reorders_and_drops_unvouched_semantic_hits(
    db_session, make_owner, make_document, make_notebook, monkeypatch
):
    monkeypatch.setattr(service, "_default_reranker", lambda: _FakeReranker())
    owner = await make_owner()
    ws = owner.workspace.id
    plain = await make_document(ws, "Plain", "Asthma mentioned once.")
    best = await make_document(ws, "Best", "The asthma guideline recommends ICS.")
    vague = await make_document(ws, "Vague", "Airway things.", embedding_axis=_TOPIC)
    notebook = await make_notebook(
        ws,
        "Nb",
        sources=[("document", plain.id), ("document", best.id), ("document", vague.id)],
    )

    result = await _search(db_session, owner, "asthma")
    ids = [p.document_id for p in _by_notebook(result)[notebook.id]]
    # Reranked first; the literal match stays; the semantic-only hit the
    # reranker scored irrelevant is gone.
    assert ids == [best.id, plain.id]


def test_search_path_is_not_captured_by_the_notebook_id_route():
    scope = {
        "type": "http",
        "method": "GET",
        "path": "/workspaces/1/notebooks/search",
        "root_path": "",
        "query_string": b"q=x",
        "headers": [],
    }
    for route in notebooks_router.routes:
        match, _ = route.matches(scope)
        if match == Match.FULL:
            assert route.endpoint is search.search_inside_notebooks
            return
    raise AssertionError("no route matched /notebooks/search")
