# Chunks on axis 5 are "about" the semantic query; everything else is orthogonal.
_TOPIC = 5


@pytest.fixture(autouse=True)
def _fixed_embedding_no_reranker(monkeypatch):
    monkeypatch.setattr(service, "_default_embedder", lambda: lambda _q: axis(_TOPIC))
    monkeypatch.setattr(service, "_default_reranker", lambda: None)


async def _search(db_session, member, q, workspace_id=None, limit=8):
    return await search.search_inside_notebooks(
        workspace_id or member.workspace.id,
        Response(),
        q=q,
        limit=limit,
        session=db_session,
        auth=member.auth,
    )


def _as(owner, user) -> SimpleNamespace:
    """``user`` acting in ``owner``'s workspace."""
    return SimpleNamespace(workspace=owner.workspace, auth=AuthContext.session(user))


def _by_notebook(result) -> dict[int, list]:
    return {hit.id: hit.passages for hit in result.notebooks}


async def test_matches_enabled_sources_and_folder_sources_but_not_disabled_ones(
    db_session, make_owner, make_document, make_folder, make_notebook
):
    owner = await make_owner()
    ws = owner.workspace.id
    direct = await make_document(ws, "Direct paper", "Wheezing and asthma in toddlers.")
    disabled = await make_document(
        ws, "Disabled paper", "Asthma action plans at school."
    )
    folder = await make_folder(ws, "Guidelines")
    in_folder = await make_document(
        ws, "Folder paper", "Asthma control in adolescents.", folder_id=folder.id
    )
    nested = await make_folder(ws, "Nested")
    nested.parent_id = folder.id
    await db_session.flush()
    deep = await make_document(
        ws, "Nested paper", "Asthma in the nested folder.", folder_id=nested.id
    )
    loose = await make_document(ws, "Not a source", "Asthma everywhere.")
    notebook = await make_notebook(
        ws,
        "Lung notebook",
        sources=[
            ("document", direct.id),
            ("document", disabled.id, False),
            ("folder", folder.id),
        ],
    )

    result = await _search(db_session, owner, "asthma")

    passages = _by_notebook(result)[notebook.id]
    found = {p.document_id for p in passages}
    assert found == {direct.id, in_folder.id}
    assert not found & {disabled.id, deep.id, loose.id}
    folder_hit = next(p for p in passages if p.document_id == in_folder.id)
    assert folder_hit.folder_name == "Guidelines"
    assert folder_hit.source_id == notebook.source_rows[2].id
    direct_hit = next(p for p in passages if p.document_id == direct.id)
    assert direct_hit.source_id == notebook.source_rows[0].id
    assert direct_hit.title == "Direct paper"
    assert direct_hit.snippet[slice(*direct_hit.highlights[0])].lower() == "asthma"


async def test_studio_outputs_and_deleting_documents_are_never_matched(
    db_session,
    make_owner,
    make_document,
    make_folder,
    make_notebook,
    make_studio_output,
):
    owner = await make_owner()
    ws = owner.workspace.id
    folder = await make_folder(ws, "Everything")
    source = await make_document(
        ws, "Real source", "Asthma triggers.", folder_id=folder.id
    )
    going = await make_document(ws, "Being deleted", "Asthma inhalers.")
    going.status = {"state": "deleting"}
    notebook = await make_notebook(
        ws, "Notebook", sources=[("folder", folder.id), ("document", going.id)]
    )
    studio = await make_studio_output(
        notebook, kind="report", artifact_format="markdown", title="Asthma report"
    )
    artifact_doc_id = studio.artifact.document_id
    # Even filed in the source folder, with a chunk that matches both ways.
    artifact_doc = await db_session.get(Document, artifact_doc_id)
    artifact_doc.folder_id = folder.id
    db_session.add(
        Chunk(
            content="Asthma report generated by the studio.",
            document_id=artifact_doc_id,
            position=0,
            embedding=axis(_TOPIC),
        )
    )
    await db_session.flush()
    assert artifact_doc.document_type == DocumentType.ARTIFACT

    result = await _search(db_session, owner, "asthma")

    ids = {p.document_id for p in _by_notebook(result)[notebook.id]}
    assert ids == {source.id}


async def test_semantic_neighbours_count_only_when_close(
    db_session, make_owner, make_document, make_notebook
):
    owner = await make_owner()
    ws = owner.workspace.id
    close = await make_document(
        ws, "Bronchiolitis", "Infant wheeze and RSV.", embedding_axis=_TOPIC
    )
    far = await make_document(
        ws, "Tax law", "Depreciation schedules.", embedding_axis=1
    )
    a = await make_notebook(ws, "Peds", sources=[("document", close.id)])
    b = await make_notebook(ws, "Taxes", sources=[("document", far.id)])

    result = await _search(db_session, owner, "breathing trouble")

    by_nb = _by_notebook(result)
    assert [p.document_id for p in by_nb[a.id]] == [close.id]
    # The nearest chunk of an unrelated notebook is still not a match.
    assert b.id not in by_nb


async def test_notes_match_by_keyword_and_prefix(db_session, make_owner, make_notebook):
    owner = await make_owner()
    ws = owner.workspace.id
    notebook = await make_notebook(ws, "Notes only")
    other = await make_notebook(ws, "Other")
    note = NotebookNote(
        notebook_id=notebook.id,
        title="School visit",
        content="The **school nurses** asked for spacer training.",
    )
    unrelated = NotebookNote(
        notebook_id=other.id, title="Groceries", content="Bread and milk."
    )
    db_session.add_all([note, unrelated])
    await db_session.flush()

    for q in ("school nurses", "nurs", "spacer training", "SPACER"):
        result = await _search(db_session, owner, q)
        by_nb = _by_notebook(result)
        assert list(by_nb) == [notebook.id], q
        (passage,) = by_nb[notebook.id]
        assert passage.kind == "note"
        assert passage.note_id == note.id
        assert passage.title == "School visit"
        assert passage.source_id is None
        assert "**" not in passage.snippet
        assert passage.highlights, q


async def test_a_shared_document_is_shown_under_each_notebook_with_its_own_link(
    db_session, make_owner, make_document, make_notebook
):
    owner = await make_owner()
    ws = owner.workspace.id
    shared = await make_document(ws, "Shared", "Montelukast dosing in children.")
    first = await make_notebook(ws, "First", sources=[("document", shared.id)])
    second = await make_notebook(ws, "Second", sources=[("document", shared.id)])

    result = await _search(db_session, owner, "montelukast")

    by_nb = _by_notebook(result)
    assert by_nb[first.id][0].source_id == first.source_rows[0].id
    assert by_nb[second.id][0].source_id == second.source_rows[0].id
    hit = next(h for h in result.notebooks if h.id == first.id)
    assert hit.title == "First"
    assert hit.updated_at is not None


async def test_results_are_capped_per_notebook_in_total_and_by_limit(
    db_session, make_owner, make_document, make_notebook
):
    owner = await make_owner()
    ws = owner.workspace.id
    docs = [
        await make_document(ws, f"Paper {i}", f"Spirometry finding number {i}.")
        for i in range(12)
    ]
    for i in range(10):
        await make_notebook(
            ws, f"Notebook {i}", sources=[("document", d.id) for d in docs]
        )

    result = await _search(db_session, owner, "spirometry")
    # 8 notebooks at most; 20 passages at most, so not all of them get 3.
    assert len(result.notebooks) == 8
    assert all(len(hit.passages) <= 3 for hit in result.notebooks)
    assert sum(len(hit.passages) for hit in result.notebooks) == 20

    limited = await _search(db_session, owner, "spirometry", limit=2)
    assert len(limited.notebooks) == 2


