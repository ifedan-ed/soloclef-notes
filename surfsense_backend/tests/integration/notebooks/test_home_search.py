"""The notebooks home search: what it searches, how it groups, who may use it.

Runs the real SQL (pgvector distance, Postgres full text) on real rows. The
query embedding is the only stand-in: a fixed unit vector per query, so which
chunks are "close" is decided by the test, not by a model.
"""

