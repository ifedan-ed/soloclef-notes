-- Saving an artifact: the document it sits on, the artifact, and its files.
-- The read side is soloclef_api/internal/artifacts, which lists and serves
-- these rows; the columns written here are the ones it and the web app read.
-- Every row is the saving account's: the composite keys (document, owner)
-- refuse an artifact that names another account's document.

-- name: DocumentPathTaken :one
SELECT EXISTS (
    SELECT 1 FROM documents
    WHERE user_id = sqlc.arg(user_id) AND path = sqlc.arg(path)::text
);

-- name: CreateArtifactDocument :one
-- status starts "pending": the document is not searchable until the indexer
-- has chunked it, and the list shows that honestly. created_at is the
-- database's.
INSERT INTO documents (
    title, document_type, document_metadata, content, content_hash,
    unique_identifier_hash, path, source_markdown, updated_at,
    user_id, status
) VALUES (
    sqlc.arg(title), 'ARTIFACT', '{}'::jsonb, sqlc.arg(content), sqlc.arg(content_hash),
    sqlc.arg(unique_identifier_hash), sqlc.arg(path), sqlc.arg(content), now(),
    sqlc.arg(user_id), '{"state": "pending"}'::jsonb
)
RETURNING id;

-- name: CreateArtifact :one
INSERT INTO artifacts (
    document_id, user_id, thread_id, format, generation,
    created_by_tool_call_id, updated_by_tool_call_id, metadata
) VALUES (
    sqlc.arg(document_id), sqlc.arg(user_id), sqlc.narg(thread_id),
    sqlc.arg(format), 1, sqlc.arg(tool_call_id), sqlc.arg(tool_call_id), sqlc.arg(metadata)
)
RETURNING id;

-- name: ReserveArtifactID :one
-- An id for an artifact whose files are stored before its rows exist (a
-- video, streamed out of the sandbox), so that their keys can name it the
-- way every artifact's keys do. The column is GENERATED BY DEFAULT, so a row
-- may be inserted with an id taken from its own sequence; an id reserved and
-- never used is a gap in the sequence and nothing else.
SELECT nextval(pg_get_serial_sequence('artifacts', 'id'))::bigint AS id;

-- name: CreateArtifactWithID :exec
-- CreateArtifact under an id ReserveArtifactID gave.
INSERT INTO artifacts (
    id, document_id, user_id, thread_id, format, generation,
    created_by_tool_call_id, updated_by_tool_call_id, metadata
) VALUES (
    sqlc.arg(id), sqlc.arg(document_id), sqlc.arg(user_id), sqlc.narg(thread_id),
    sqlc.arg(format), 1, sqlc.arg(tool_call_id), sqlc.arg(tool_call_id), sqlc.arg(metadata)
);

-- name: LinkDocumentToArtifact :exec
-- The owner is named although the id was made a statement ago in the same
-- transaction: no statement here writes a row by its id alone.
UPDATE documents
SET document_metadata = jsonb_build_object('artifact_id', sqlc.arg(artifact_id)::bigint)
WHERE id = sqlc.arg(document_id) AND user_id = sqlc.arg(user_id);

-- name: CreateArtifactFile :one
-- role is 'primary' (the artifact itself) or 'preview' (a PDF rendering of
-- it, which the page shows for a Word document or a deck). An artifact has
-- at most one of each.
INSERT INTO artifact_files (
    artifact_id, role, storage_backend, storage_key, original_filename,
    mime_type, size_bytes, checksum_sha256
) VALUES (
    sqlc.arg(artifact_id), sqlc.arg(role)::artifact_file_role, sqlc.arg(storage_backend), sqlc.arg(storage_key),
    sqlc.arg(original_filename), sqlc.arg(mime_type), sqlc.arg(size_bytes), sqlc.arg(checksum_sha256)
)
RETURNING id;
