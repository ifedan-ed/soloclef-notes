// Package nextcloudtest is a stand-in Nextcloud for tests: one account's
// files behind real HTTP, answering the WebDAV requests package nextcloud
// sends (PROPFIND at depth 0 and 1, SEARCH, GET, PUT, DELETE) the way
// Nextcloud answers them, checking the app password, and recording what
// it was asked. It is a test's server, never a deployment's.
package nextcloudtest

import (
	"fmt"
	"html"
	"io"
	"net/http"
	"net/http/httptest"
	"net/url"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"sync"
	"testing"

	"git.danvics.com/danvics/soloclef/soloclef_connectors/nextcloud"
)

// The account the server holds.
const (
	User     = "ada"
	Login    = "ada@example.org"
	Password = "app-password"
)

// Node is one file or folder.
type Node struct {
	Folder  bool
	Content string
	// Size, when set, is a file of that many generated bytes instead of
	// Content: a large download that the test never holds either.
	Size int64
	ETag string
	// NoSize leaves the length out of the listing, as a server may.
	NoSize bool
	// FileID is Nextcloud's number for the file; New gives every node one.
	FileID string
}

// Server is the stand-in.
type Server struct {
	t      testing.TB
	server *httptest.Server
	mu     sync.Mutex
	files  map[string]Node
	nextID int
	asked  []string
	logins []string
	// searches is the body of every SEARCH.
	searches []string
	trashed  []string
	before   func(http.ResponseWriter, *http.Request) bool
	// ReadOnly makes any write a test failure: for a caller that must
	// never write.
	ReadOnly bool
}

// New starts a server holding files, keyed by their path ("/a/b.pdf").
// Every folder a path passes through must be listed too.
func New(t testing.TB, files map[string]Node) *Server {
	t.Helper()
	s := &Server{t: t, files: map[string]Node{}, nextID: 100}
	paths := make([]string, 0, len(files))
	for path := range files {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		node := files[path]
		if node.FileID == "" {
			node.FileID = s.newID()
		}
		s.files[path] = node
	}
	s.server = httptest.NewServer(http.HandlerFunc(s.serve))
	t.Cleanup(s.server.Close)
	return s
}

func (s *Server) newID() string {
	s.nextID++
	return strconv.Itoa(s.nextID)
}

// URL is the server's address.
func (s *Server) URL() string { return s.server.URL }

// Transport is how a client reaches it.
func (s *Server) Transport() http.RoundTripper { return s.server.Client().Transport }

// Account is the account, with the right app password.
func (s *Server) Account() nextcloud.Account {
	return nextcloud.Account{BaseURL: s.server.URL, Username: User, LoginName: Login, AppPassword: Password}
}

// Before, when set, may answer a request itself; it returns true if it did.
func (s *Server) Before(answer func(http.ResponseWriter, *http.Request) bool) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.before = answer
}

// Requests is every request so far, as "METHOD path".
func (s *Server) Requests() []string {
	s.mu.Lock()
	defer s.mu.Unlock()
	return append([]string(nil), s.asked...)
}

// Logins is the user name each request authenticated as.
func (s *Server) Logins() []string {
	s.mu.Lock()
	defer s.mu.Unlock()
	return append([]string(nil), s.logins...)
}

// Searches is the body of every SEARCH.
func (s *Server) Searches() []string {
	s.mu.Lock()
	defer s.mu.Unlock()
	return append([]string(nil), s.searches...)
}

// Trashed is every path deleted, in order.
func (s *Server) Trashed() []string {
	s.mu.Lock()
	defer s.mu.Unlock()
	return append([]string(nil), s.trashed...)
}

// File is what the server holds at path now.
func (s *Server) File(path string) (Node, bool) {
	s.mu.Lock()
	defer s.mu.Unlock()
	node, found := s.files[path]
	return node, found
}

// Put places a node, as another client of the same account would.
func (s *Server) Put(path string, node Node) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if node.FileID == "" {
		node.FileID = s.newID()
	}
	s.files[path] = node
}

const prefix = "/remote.php/dav/files/" + User

func (s *Server) serve(response http.ResponseWriter, request *http.Request) {
	if request.Method == "SEARCH" {
		s.search(response, request)
		return
	}
	path, err := url.PathUnescape(strings.TrimPrefix(request.URL.EscapedPath(), prefix))
	if err != nil || !strings.HasPrefix(request.URL.Path, prefix) {
		http.NotFound(response, request)
		return
	}
	if path = "/" + strings.Trim(path, "/"); path == "//" {
		path = "/"
	}
	user, password, _ := request.BasicAuth()
	s.mu.Lock()
	s.asked = append(s.asked, request.Method+" "+path)
	s.logins = append(s.logins, user)
	before := s.before
	held, found := s.files[path]
	s.mu.Unlock()

	if before != nil && before(response, request) {
		return
	}
	if user != Login || password != Password {
		response.WriteHeader(http.StatusUnauthorized)
		return
	}
	if path == "/" {
		held, found = Node{Folder: true, FileID: "1"}, true
	}
	switch request.Method {
	case http.MethodPut:
		s.put(response, request, path, found)
		return
	case http.MethodDelete:
		s.delete(response, path, found)
		return
	}
	if !found {
		http.NotFound(response, request)
		return
	}
	switch request.Method {
	case "PROPFIND":
		listed := []string{path}
		if request.Header.Get("Depth") == "1" && held.Folder {
			s.mu.Lock()
			for candidate := range s.files {
				if candidate != path && nextcloud.ParentOf(candidate) == path {
					listed = append(listed, candidate)
				}
			}
			s.mu.Unlock()
			sort.Strings(listed[1:])
		}
		var body strings.Builder
		body.WriteString(`<?xml version="1.0"?><d:multistatus xmlns:d="DAV:" xmlns:oc="http://owncloud.org/ns">`)
		for _, each := range listed {
			s.mu.Lock()
			described := s.files[each]
			s.mu.Unlock()
			if each == "/" {
				described = Node{Folder: true, FileID: "1"}
			}
			body.WriteString(describe(each, described))
		}
		body.WriteString(`</d:multistatus>`)
		response.Header().Set("Content-Type", "application/xml")
		response.WriteHeader(http.StatusMultiStatus)
		_, _ = io.WriteString(response, body.String())
	case http.MethodGet:
		if held.Folder {
			response.WriteHeader(http.StatusMethodNotAllowed)
			return
		}
		if held.Size > 0 {
			_, _ = io.Copy(response, &generated{left: held.Size})
			return
		}
		_, _ = io.WriteString(response, held.Content)
	default:
		s.t.Errorf("nextcloudtest: the client sent %s", request.Method)
		response.WriteHeader(http.StatusMethodNotAllowed)
	}
}

// put stores a file the way Nextcloud does: 409 when the folder is not
// there, 412 when If-None-Match: * meets a file that is, 201 for a new one
// and 204 for a replaced one.
func (s *Server) put(response http.ResponseWriter, request *http.Request, path string, exists bool) {
	if s.ReadOnly {
		s.t.Errorf("nextcloudtest: a read-only client sent PUT %s", path)
	}
	content, _ := io.ReadAll(request.Body)
	s.mu.Lock()
	defer s.mu.Unlock()
	parent, parentFound := s.files[nextcloud.ParentOf(path)]
	switch {
	case nextcloud.ParentOf(path) != "/" && (!parentFound || !parent.Folder):
		response.WriteHeader(http.StatusConflict)
		return
	case exists && request.Header.Get("If-None-Match") == "*":
		response.WriteHeader(http.StatusPreconditionFailed)
		return
	}
	node := Node{Content: string(content), ETag: fmt.Sprintf("etag-%d", len(content)), FileID: s.newID()}
	s.files[path] = node
	if exists {
		response.WriteHeader(http.StatusNoContent)
		return
	}
	response.WriteHeader(http.StatusCreated)
}

// delete removes a file, or a folder and all under it, into the bin.
func (s *Server) delete(response http.ResponseWriter, path string, exists bool) {
	if s.ReadOnly {
		s.t.Errorf("nextcloudtest: a read-only client sent DELETE %s", path)
	}
	if !exists || path == "/" {
		response.WriteHeader(http.StatusNotFound)
		return
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	for candidate := range s.files {
		if candidate == path || strings.HasPrefix(candidate, path+"/") {
			delete(s.files, candidate)
		}
	}
	s.trashed = append(s.trashed, path)
	response.WriteHeader(http.StatusNoContent)
}

// searchLiteral is the pattern of a SEARCH request's `like`.
var searchLiteral = regexp.MustCompile(`<d:literal>([^<]*)</d:literal>`)

// search answers a WebDAV SEARCH the way Nextcloud does: at the DAV root,
// for the account in the scope, every file and folder whose name contains
// the pattern's text without regard to case, and the scope itself first
// (which a client must leave out), in an order a client must not rely on.
func (s *Server) search(response http.ResponseWriter, request *http.Request) {
	user, password, _ := request.BasicAuth()
	raw, _ := io.ReadAll(request.Body)
	s.mu.Lock()
	s.asked = append(s.asked, "SEARCH "+request.URL.Path)
	s.logins = append(s.logins, user)
	s.searches = append(s.searches, string(raw))
	before := s.before
	s.mu.Unlock()
	if before != nil && before(response, request) {
		return
	}
	if user != Login || password != Password {
		response.WriteHeader(http.StatusUnauthorized)
		return
	}
	found := searchLiteral.FindStringSubmatch(string(raw))
	if request.URL.Path != "/remote.php/dav/" || found == nil || !strings.Contains(string(raw), "<d:href>/files/"+User+"</d:href>") {
		response.WriteHeader(http.StatusBadRequest)
		return
	}
	term := strings.ToLower(strings.Trim(html.UnescapeString(found[1]), "%"))
	var body strings.Builder
	body.WriteString(`<?xml version="1.0"?><d:multistatus xmlns:d="DAV:" xmlns:oc="http://owncloud.org/ns">`)
	body.WriteString(describe("/", Node{Folder: true, FileID: "1"}))
	s.mu.Lock()
	paths := make([]string, 0, len(s.files))
	for path := range s.files {
		paths = append(paths, path)
	}
	sort.Sort(sort.Reverse(sort.StringSlice(paths)))
	for _, path := range paths {
		parts := nextcloud.PathParts(path)
		if strings.Contains(strings.ToLower(parts[len(parts)-1]), term) {
			body.WriteString(describe(path, s.files[path]))
		}
	}
	s.mu.Unlock()
	body.WriteString(`</d:multistatus>`)
	response.Header().Set("Content-Type", "application/xml")
	response.WriteHeader(http.StatusMultiStatus)
	_, _ = io.WriteString(response, body.String())
}

// describe is one <d:response>, written the way Nextcloud writes one: the
// properties it has under a 200 propstat, the ones it lacks under a 404.
func describe(path string, held Node) string {
	segments := nextcloud.PathParts(path)
	for index, segment := range segments {
		segments[index] = url.PathEscape(segment)
	}
	// "&" is legal in a URL path and not in XML text.
	href := html.EscapeString(prefix + "/" + strings.Join(segments, "/"))
	if held.Folder && path != "/" {
		href += "/"
	}
	id := `<oc:fileid>` + held.FileID + `</oc:fileid>`
	if held.Folder {
		return `<d:response><d:href>` + href + `</d:href><d:propstat><d:prop>` +
			`<d:resourcetype><d:collection/></d:resourcetype><d:getlastmodified>Tue, 03 Feb 2026 04:05:06 GMT</d:getlastmodified>` +
			`<d:getetag>"folder-etag"</d:getetag><oc:size>4096</oc:size>` + id + `</d:prop><d:status>HTTP/1.1 200 OK</d:status></d:propstat>` +
			`<d:propstat><d:prop><d:getcontentlength/><d:getcontenttype/></d:prop><d:status>HTTP/1.1 404 Not Found</d:status></d:propstat></d:response>`
	}
	length := int64(len(held.Content))
	if held.Size > 0 {
		length = held.Size
	}
	size := fmt.Sprintf(`<d:getcontentlength>%d</d:getcontentlength>`, length)
	missing := ""
	if held.NoSize {
		size, missing = "", `<d:propstat><d:prop><d:getcontentlength/></d:prop><d:status>HTTP/1.1 404 Not Found</d:status></d:propstat>`
	}
	etag := held.ETag
	if etag == "" {
		etag = "etag-of-" + path
	}
	etag = html.EscapeString(etag)
	kind := "application/pdf"
	if strings.HasSuffix(strings.ToLower(path), ".md") || strings.HasSuffix(strings.ToLower(path), ".txt") {
		kind = "text/plain"
	}
	return `<d:response><d:href>` + href + `</d:href><d:propstat><d:prop><d:resourcetype/>` + size +
		`<d:getlastmodified>Tue, 03 Feb 2026 04:05:06 GMT</d:getlastmodified><d:getcontenttype>` + kind + `</d:getcontenttype>` +
		`<d:getetag>&quot;` + etag + `&quot;</d:getetag>` + id + `</d:prop><d:status>HTTP/1.1 200 OK</d:status></d:propstat>` + missing + `</d:response>`
}

// generated yields `left` bytes of a repeating pattern without holding
// them.
type generated struct{ left int64 }

func (g *generated) Read(buffer []byte) (int, error) {
	if g.left == 0 {
		return 0, io.EOF
	}
	if int64(len(buffer)) > g.left {
		buffer = buffer[:g.left]
	}
	for index := range buffer {
		buffer[index] = byte('a' + index%26)
	}
	g.left -= int64(len(buffer))
	return len(buffer), nil
}
