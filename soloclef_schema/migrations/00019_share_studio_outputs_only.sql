-- +goose Up

-- The owner's decision (2026-11-13): "only artifacts should be shareable".
-- A public link now reaches one Studio output (a mind map, a report, a deck,
-- flashcards, a quiz, audio, a video, an infographic, a data table) and
-- nothing else. The two other kinds of link go, with every row they had:
--
--   * a chat's link, a frozen copy of a conversation in
--     public_chat_snapshots (thread_id set), and the "copy this chat into my
--     account" that a reader could make from one (new_chat_threads'
--     cloned_from_* columns);
--   * a notebook's live link (notebook_public_links), which followed the
--     notebook and its newest chat.
--
-- Deleting the rows is the revoke: a token with no row is a 404 everywhere
-- a link is read. An output's link keeps its row, its token, its expiry and
-- its frozen copy untouched; only the table's name and the columns that
-- existed for chats change, so every link already sent keeps working.

-- Chat links. Revoked first, so the columns below hold nothing when they go.
DELETE FROM public_chat_snapshots WHERE thread_id IS NOT NULL;

-- A copied chat stays its reader's own conversation; it only forgets which
-- link it came from, which nothing reads any more. Dropping the columns
-- takes their indexes and the foreign key to the snapshots with them.
ALTER TABLE new_chat_threads
    DROP COLUMN cloned_from_thread_id,
    DROP COLUMN cloned_from_snapshot_id,
    DROP COLUMN cloned_at;

-- What is left is a table of output links. The chat-only columns go (the
-- thread, the ids of the frozen messages), with the constraints that were
-- only about them; every row names its output, so the column says so.
ALTER TABLE public_chat_snapshots
    DROP CONSTRAINT ck_public_snapshot_one_subject,
    DROP CONSTRAINT uq_snapshot_thread_content_hash,
    DROP COLUMN thread_id,
    DROP COLUMN message_ids,
    ALTER COLUMN notebook_output_id SET NOT NULL;

-- Named for what it holds now. Every name that carried the old one moves
-- with it, so a constraint error or a plan reads as the table it is about.
ALTER TABLE public_chat_snapshots RENAME TO output_public_links;
ALTER SEQUENCE public_chat_snapshots_id_seq RENAME TO output_public_links_id_seq;
ALTER TABLE output_public_links RENAME CONSTRAINT public_chat_snapshots_pkey TO output_public_links_pkey;
ALTER TABLE output_public_links RENAME CONSTRAINT public_chat_snapshots_user_id_fkey TO output_public_links_user_id_fkey;
ALTER TABLE output_public_links RENAME CONSTRAINT public_chat_snapshots_notebook_output_id_fkey TO output_public_links_notebook_output_id_fkey;
ALTER TABLE output_public_links RENAME CONSTRAINT uq_public_chat_snapshots_share_token TO uq_output_public_links_share_token;
ALTER INDEX ix_public_chat_snapshots_user_id RENAME TO ix_output_public_links_user_id;
ALTER INDEX ix_public_chat_snapshots_notebook_output_id RENAME TO ix_output_public_links_notebook_output_id;

-- Notebook live links, rows and table.
DROP TABLE notebook_public_links;

-- +goose Down

-- The structure comes back as 00001 made it, empty: the revoked links and
-- which chats were copied from which link are not kept anywhere, so nothing
-- of them can return. Output links come back as they are.

-- A read-only public link to a whole notebook, as 00001 made it: the token
-- was the whole authorisation, until it expired or was revoked.
CREATE TABLE notebook_public_links (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notebook_id bigint NOT NULL,
    user_id     uuid NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
    share_token varchar(128) NOT NULL,
    expires_at  timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_notebook_public_links_notebook UNIQUE (notebook_id),
    CONSTRAINT uq_notebook_public_links_share_token UNIQUE (share_token),
    CONSTRAINT notebook_public_links_notebook_owner_fkey FOREIGN KEY (notebook_id, user_id)
        REFERENCES notebooks (id, user_id) ON DELETE CASCADE
);
CREATE INDEX ix_notebook_public_links_user_id ON notebook_public_links (user_id);

ALTER INDEX ix_output_public_links_notebook_output_id RENAME TO ix_public_chat_snapshots_notebook_output_id;
ALTER INDEX ix_output_public_links_user_id RENAME TO ix_public_chat_snapshots_user_id;
ALTER TABLE output_public_links RENAME CONSTRAINT uq_output_public_links_share_token TO uq_public_chat_snapshots_share_token;
ALTER TABLE output_public_links RENAME CONSTRAINT output_public_links_notebook_output_id_fkey TO public_chat_snapshots_notebook_output_id_fkey;
ALTER TABLE output_public_links RENAME CONSTRAINT output_public_links_user_id_fkey TO public_chat_snapshots_user_id_fkey;
ALTER TABLE output_public_links RENAME CONSTRAINT output_public_links_pkey TO public_chat_snapshots_pkey;
ALTER SEQUENCE output_public_links_id_seq RENAME TO public_chat_snapshots_id_seq;
ALTER TABLE output_public_links RENAME TO public_chat_snapshots;

-- An output link froze no messages, which is the empty list 00001's rows
-- for outputs held; the default only fills the existing rows and then goes.
ALTER TABLE public_chat_snapshots
    ALTER COLUMN notebook_output_id DROP NOT NULL,
    ADD COLUMN thread_id bigint REFERENCES new_chat_threads (id) ON DELETE CASCADE,
    ADD COLUMN message_ids bigint[] NOT NULL DEFAULT '{}',
    ADD CONSTRAINT uq_snapshot_thread_content_hash UNIQUE (thread_id, content_hash),
    ADD CONSTRAINT ck_public_snapshot_one_subject CHECK (num_nonnulls(thread_id, notebook_output_id) = 1);
ALTER TABLE public_chat_snapshots ALTER COLUMN message_ids DROP DEFAULT;

ALTER TABLE new_chat_threads
    ADD COLUMN cloned_from_thread_id bigint REFERENCES new_chat_threads (id) ON DELETE SET NULL,
    ADD COLUMN cloned_from_snapshot_id bigint,
    ADD COLUMN cloned_at timestamptz,
    ADD CONSTRAINT new_chat_threads_cloned_from_snapshot_id_fkey
        FOREIGN KEY (cloned_from_snapshot_id) REFERENCES public_chat_snapshots (id) ON DELETE SET NULL;
CREATE INDEX ix_new_chat_threads_cloned_from_thread_id ON new_chat_threads (cloned_from_thread_id);
CREATE INDEX ix_new_chat_threads_cloned_from_snapshot_id ON new_chat_threads (cloned_from_snapshot_id);
