-- foreign key to "user".
DROP TABLE app_feedback;

-- +goose Down

-- The table as 00018 made it, and empty: what was sent cannot come back.
CREATE TABLE app_feedback (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app         text NOT NULL,
    platform    text NOT NULL,
    app_version text NOT NULL,
    stars       smallint NOT NULL,
    comment     text NOT NULL DEFAULT '',
    contact_ok  boolean NOT NULL,
    user_id     uuid REFERENCES "user" (id) ON DELETE CASCADE,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_app_feedback_app CHECK (char_length(app) BETWEEN 1 AND 40),
    CONSTRAINT ck_app_feedback_platform CHECK (platform IN ('ios', 'android', 'web')),
    CONSTRAINT ck_app_feedback_app_version CHECK (char_length(app_version) BETWEEN 1 AND 64),
    CONSTRAINT ck_app_feedback_stars CHECK (stars BETWEEN 1 AND 5),
    CONSTRAINT ck_app_feedback_comment CHECK (char_length(comment) <= 2000),
    CONSTRAINT ck_app_feedback_user_is_soloclefs CHECK (user_id IS NULL OR app = 'soloclef')
);
CREATE INDEX ix_app_feedback_newest ON app_feedback (created_at DESC, id DESC);
CREATE INDEX ix_app_feedback_user_id ON app_feedback (user_id) WHERE user_id IS NOT NULL;
