-- Ratings and comments from every one of the owner's apps (Soloclef's web
-- and phone, and the other apps that post with their own app key), read
-- only by the site's administrators (soloclef_api/internal/appfeedback).
--
-- One row is exactly what the app sent and nothing more: no address, no IP,
-- no device id. The one link to a person is user_id, and only Soloclef's
-- own signed-in feedback has it (the ck_app_feedback_user_is_soloclefs
-- check), so a reply can be sent when the person ticked contact_ok. It
-- cascades: an account that is erased takes its feedback, comment
-- included, with it.
--
-- The limits are checked here as well as in the route, so a row that breaks
-- one cannot exist whoever writes it.
CREATE TABLE app_feedback (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app         text NOT NULL,
    platform    text NOT NULL,
    app_version text NOT NULL,
    stars       smallint NOT NULL,
    comment     text NOT NULL DEFAULT '',
    contact_ok  boolean NOT NULL,
    user_id     uuid REFERENCES "user" (id) ON DELETE CASCADE,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_app_feedback_app CHECK (char_length(app) BETWEEN 1 AND 40),
    CONSTRAINT ck_app_feedback_platform CHECK (platform IN ('ios', 'android', 'web')),
    CONSTRAINT ck_app_feedback_app_version CHECK (char_length(app_version) BETWEEN 1 AND 64),
    CONSTRAINT ck_app_feedback_stars CHECK (stars BETWEEN 1 AND 5),
    CONSTRAINT ck_app_feedback_comment CHECK (char_length(comment) <= 2000),
    CONSTRAINT ck_app_feedback_user_is_soloclefs CHECK (user_id IS NULL OR app = 'soloclef')
);

-- The list is read newest first, by when each item was written with the id
-- as the tie-break, and paged from a row in that order; this index serves
-- the order, the paging and the date range.
CREATE INDEX ix_app_feedback_newest ON app_feedback (created_at DESC, id DESC);
-- The account's own rows, for the erasure's cascade.
CREATE INDEX ix_app_feedback_user_id ON app_feedback (user_id) WHERE user_id IS NOT NULL;

